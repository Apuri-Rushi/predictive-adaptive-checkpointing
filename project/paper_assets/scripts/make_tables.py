def lost_tier_table(num, rho, stem, label):
    fd = pd.read_csv(C.ANALYSIS[rho] / "failures_detail.csv")
    ps = C.policy_summary(rho)
    lost = fd.groupby(["run", "tier_at_failure"]).lost_h.sum().unstack().reindex(columns=C.TIERS).fillna(0)
    rows, recs = [], []
    for p in POLICIES:
        v = lost.loc[p]
        tot = C.getv(ps, "all", p, "lost_work_h")
        assert abs(v.sum() - tot) < 1e-6 * max(1, tot), (p, v.sum(), tot)
        rows.append([pname(p), *[fmt(v[t], 1) for t in C.TIERS], fmt(v.sum(), 1)])
        recs.append({"policy": p, **v.to_dict(), "total": v.sum()})
    src(stem, C.ANALYSIS[rho] / "failures_detail.csv", C.ANALYSIS[rho] / "policy_summary.csv")
    n = fd[fd.run == "E1_none"].tier_at_failure.value_counts()
    notes = (f"ρ = {rho}. Lost computation (h) grouped by the risk tier in force at the failure instant (LOW n = {n['LOW']}, "
             f"MEDIUM n = {n['MEDIUM']}, HIGH n = {n['HIGH']} failures). Row totals equal the lost-work totals of the overall "
             "comparison. Point estimates only; with 27 – 110 failures per tier, differences are uncertain.")
    write_table(num, stem, label, f"Lost computation by risk tier at failure, ρ = {rho}.",
                ["Policy", "LOW", "MEDIUM", "HIGH", "Total"], rows, pd.DataFrame(recs), colspec="lrrrr", notes=notes,
                midrules=[1, 3, 5, 7, 9])


