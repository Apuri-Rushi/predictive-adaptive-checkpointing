# ------------------------------------------------------------------ formatting
def fmt(v, dec=None, sign=False):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "--"
    v = float(v)
    if dec is None:
        a = abs(v)
        if v == 0:
            return "0"
        if a < 1e-4:
            return ("+" if sign and v > 0 else "") + f"{v:.1e}"
        dec = 0 if a >= 1000 else 1 if a >= 100 else 2 if a >= 1 else 3 if a >= 0.01 else 4
    s = f"{v:,.{dec}f}"
    if sign and v > 0:
        s = "+" + s
    return s


def tex(s):
    s = str(s)
    for a, b in [("\\", r"\textbackslash{}"), ("%", r"\%"), ("&", r"\&"), ("#", r"\#"), ("_", r"\_"),
                 ("<", "$<$"), (">", "$>$"), ("|", r"$|$")]:
        s = s.replace(a, b)
    s = re.sub(r"(?<![\w$])-(?=\d)", "$-$", s)   # minus signs before numbers
    for a, b in [("−", "$-$"), ("≤", r"$\le$"), ("≥", r"$\ge$"), ("×", r"$\times$"), ("ρ", r"$\rho$"),
                 ("β", r"$\beta$"), ("T0", r"$T_0$"), ("τ", r"$\tau$"), ("Δ", r"$\Delta$"), ("…", r"\dots{}"),
                 ("→", r"$\to$"), ("√", r"$\surd$"), ("÷", "/"), ("–", "--"), ("—", "---")]:
        s = s.replace(a, b)
    bad = [ch for ch in s if ord(ch) > 127]
    assert not bad, (bad, s)
    return s


def write_table(num, stem, label, caption, header, rows, df, colspec=None, wide=False, notes=None, groups=None,
                midrules=None, fontsize="footnotesize"):
    """rows: list of lists of display strings (already formatted, raw text); df: raw CSV source."""
    CSV_DIR.mkdir(parents=True, exist_ok=True)
    TEX_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(CSV_DIR / f"{stem}.csv", index=False)
    env = "table*" if wide else "table"
    colspec = colspec or ("l" + "r" * (len(header) - 1))
    L = [f"% Auto-generated by paper_assets/scripts/make_tables.py from {', '.join(SOURCES.get(stem, []))}",
         f"\\begin{{{env}}}[!t]", "\\centering", f"\\caption{{{tex(caption)}}}", f"\\label{{{label}}}",
         f"\\{fontsize}", "\\setlength{\\tabcolsep}{4pt}", f"\\begin{{tabular}}{{{colspec}}}", "\\toprule"]
    if groups:
        L.append(" & ".join(f"\\multicolumn{{{n}}}{{c}}{{{tex(g)}}}" if n > 1 else tex(g) for g, n in groups) + r" \\")
        start = 1
        cm = []
        for g, n in groups:
            if g and n > 1:
                cm.append(f"\\cmidrule(lr){{{start}-{start + n - 1}}}")
            start += n
        L.append(" ".join(cm))
    L.append(" & ".join(tex(h) for h in header) + r" \\")
    L.append("\\midrule")
    for i, r in enumerate(rows):
        if midrules and i in midrules and i > 0:
            L.append("\\midrule")
        L.append(" & ".join(tex(c) for c in r) + r" \\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    if notes:
        L.append("\\par\\smallskip")
        width = "0.97\\textwidth" if wide else "0.97\\columnwidth"
        L.append("\\parbox{" + width + "}{\\scriptsize " + tex(notes) + "}")
    L.append(f"\\end{{{env}}}")
    (TEX_DIR / f"{stem}.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    INDEX.append({"number": num, "stem": stem, "label": label, "caption": caption, "wide": wide,
                  "sources": SOURCES.get(stem, []), "notes": notes or ""})


