def strata_table(num, rho, stem, label):
    ps = C.policy_summary(rho)
    rows, recs = [], []
    for p in POLICIES:
        f = ps[(ps.stratum == "failing") & (ps.policy == p)].iloc[0]
        n = ps[(ps.stratum == "non_failing") & (ps.policy == p)].iloc[0]
        rows.append([pname(p), fmt(f.deadline_miss_pct), f"[{fmt(f.deadline_miss_pct_ci_lo)}, {fmt(f.deadline_miss_pct_ci_hi)}]",
                     fmt(f.lost_work_h), fmt(f.overhead_pct_of_useful), fmt(f.checkpoints_per_job),
                     fmt(n.deadline_miss_pct), fmt(n.overhead_pct_of_useful), fmt(n.checkpoints_per_job),
                     fmt(n.queue_mean_h_per_job)])
        recs.append({"policy": p, **{f"failing_{k}": f[k] for k in f.index if k not in ("stratum", "policy")},
                     **{f"non_failing_{k}": n[k] for k in n.index if k not in ("stratum", "policy")}})
    src(stem, C.ANALYSIS[rho] / "policy_summary.csv")
    notes = (f"ρ = {rho}. Failing hosts: the 175 hosts whose drive failed in June (one failure each); non-failing: 110,673 "
             "hosts. Non-failing hosts lose no work by construction. CI: host-clustered bootstrap within the stratum.")
    write_table(num, stem, label, f"Failing versus non-failing hosts, ρ = {rho}.",
                ["Policy", "Miss %", "95 % CI", "Lost (h)", "Ovh. %", "Ckpt/job", "Miss %", "Ovh. %", "Ckpt/job", "Queue h/job"],
                rows, pd.DataFrame(recs), colspec="l" + "r" * 9, wide=True, notes=notes,
                groups=[("", 1), ("Failing hosts (175)", 5), ("Non-failing hosts (110,673)", 4)], midrules=[1, 3, 5, 7, 9])


